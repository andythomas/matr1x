def delta(data):
    """
    Resolves transport data acquired using the delta method

    Parameters
    -------
    data : np.array
      Array of data with dimension 'm' containing e.g. voltage.
      Format must be [value for +I, value for -I, value for +I, ...]

    Returns
    -------
    pos : np.array
      Array with dimension 'm//2' containing the contribution symmetric in
      current
    neg : np.array
      Array with dimension 'm//2' containing the contribution antisymmetric in
      current
    """
    if len(data) % 2:
        return (np.add(data[:-1:2], data[1::2])/2,
                np.subtract(data[:-1:2], data[1::2])/2)
    else:
        return (np.add(data[::2], data[1::2])/2,
                np.subtract(data[::2], data[1::2])/2)


def delta3p(data):
    """
    Resolves transport data acquired using the three point delta method.
    Should have superior rejection of drifts compared to 2p delta method.

    Parameters
    -------
    data : np.array
      Array of data with dimension 'm' containing e.g. voltage.
      Array contains triples of values with format
      [value1 for +I, value1 for -I, value1 for +I, value2 for +I, ..]

    Returns
    -------
    pos : np.array
      Array with dimension 'm//3' containing the contribution symmetric in
      current
    neg : np.array
      Array with dimension 'm//3' containing the contribution antisymmetric in
      current
    """
    off = len(data) % 3
    if 0 != off:
        return (np.add(np.add(data[:-off:3], data[2:-off:3]),
                       2*data[1:-off:3])/4,
                np.subtract(np.add(data[:-off:3], data[2:-off:3]),
                            2*data[1:-off:3])/4)
    else:
        return (np.add(np.add(data[::3], data[2::3]), 2*data[1::3])/4,
                np.subtract(np.add(data[::3], data[2::3]), 2*data[1::3])/4)
