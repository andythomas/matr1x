def detect_hdf5(filename):
    """
    Detect if an existing file is in the HDF5 format by inspecting the first 4 bytes.

    Parameters
    ----------
    filename : str
        The path of the file to be inspected

    Returns
    -------
    bool
        HDF5 yes (True) or no (False)
    """
    with open(filename, "rb") as file:
        first_bytes = file.read(4)
    if first_bytes == b'\x89HDF':
        return True
    return False


def get_latest_datafile(path=None, basename=None):
    """
    Automagically find latest datafile in 'path' which follows the pattern of 'basename'.

    Note that a trailing "_[integer]" is removed from basename to
    find the latest file recorded with the same basename. If path is None the path
    is taken from 'basename'. 'basename' can be an
    input file name or a data file name which was given to matrix. If no
    basename is given the latest data file by creation date will be returned in
    path. If both path and basename are None os.curdir will be used.

    Parameters
    ----------
    path: str or None, optional
      path in which the latest datafile should be determined
    basename: str or None, optional
      an example filename or input filename used to filter files in path.
    """
    basepath = None
    basewoext = None
    if basename:
        basepath, basefilename = split(basename)
        basewoext = splitext(basefilename)[0]
        basewoext = re.sub(r"(_\d+)$", "", basewoext)

    # determine used file path
    if path:
        usedpath = path
    elif basepath:
        usedpath = basepath
    else:
        usedpath = os.curdir

    # obtain file list and filter it
    allfiles = os.listdir(usedpath)
    filelist = filter(lambda f: isfile(join(usedpath, f)), allfiles)
    if basewoext:  # filter file list by file extension/basename
        files = natsorted(
            [f for f in filelist if
             re.search(fr'^({basewoext})(_\d+)?(\.h5)?\.ma\d$', f)]
        )
    else:  # filter by file extension and sort by date
        files = sorted(
            [f for f in filelist if re.search(r'(_\d+)?(\.h5)?\.ma\d$', f)],
            key=lambda f: os.path.getctime(join(usedpath, f))
        )

    if len(files) > 0:
        return join(usedpath, files[-1])
    return None


def _parse_query_string(query: str):
    """
    Parse a System query string into a structured dictionary.

    This function takes a multi-line query string and parses it into a nested dictionary
    structure. It handles device entries, key-value pairs, and multi-line values.

    Parameters
    ----------
    query : str
        The multi-line query string to be parsed.

    Returns
    -------
    dict
        A nested dictionary containing the parsed data. The top-level keys are device names,
        and their values are dictionaries of key-value pairs for each device.
    """
    parsed_data = {}
    current_key = None
    current_device = None
    multiline_value = []
    in_multiline = False
    in_device = False  # Track whether we're inside a device

    for line in query.splitlines():
        line = line.rstrip(
            "\n"
        )  # Only remove the newline character, keep all spaces intact

        if not line:
            continue

        # Handle multiline value continuation
        if in_multiline:
            if line.startswith("# "):  # Continuation of a multiline value
                multiline_value.append(line[2:])  # Remove leading "# "
            else:
                # End of multiline entry, store it
                if in_device:
                    parsed_data[current_device][current_key] = "\n".join(
                        multiline_value
                    ).rstrip('"')
                else:
                    parsed_data[current_key] = "\n".join(multiline_value).rstrip('"')

                in_multiline = False
                multiline_value = []
                # Process the new line (e.g., new device or entry)
                if not line.startswith("#"):
                    current_device = line
                    parsed_data[current_device] = {}
                    in_device = True

        # Detect new device or global entry start
        if not line.startswith("#") and ":" not in line:  # New device (without ':')
            current_device = line.strip()
            parsed_data[current_device] = {}
            in_device = True

        elif ":" in line and not in_multiline:
            # Process key-value pair
            key, value = line.split(":", 1)  # Split only on the first ":"
            key = key.strip()
            value = value.strip()

            # Handle if this is a top-level key (like 'User script')
            if current_device is None or (
                not line.startswith("#") and current_device is not None
            ):
                # We assume this is a global entry, not a device-related one
                in_device = False
                current_device = None

            # Handle multiline string (still enclosed in quotes)
            if value.startswith('"') and not value.endswith(
                '"'
            ):  # Multiline entry starts here
                current_key = key
                multiline_value.append(value.strip('"'))  # Remove the opening quote
                in_multiline = True
                in_device = current_device is not None
            else:
                # Handle quoted strings or other evaluable types
                if value.startswith('"') and value.endswith('"'):
                    parsed_value = value.strip('"')
                else:
                    # Use ast.literal_eval() to parse any non-string value (lists, ints, floats, etc.)
                    try:
                        parsed_value = ast.literal_eval(value)
                    except (ValueError, SyntaxError):
                        parsed_value = value  # If not evaluable, store as string

                # Place the parsed key-value in the right dictionary (global or device)
                if in_device:
                    # Remove leading "# " from the key if it's in a device dictionary
                    key = key.lstrip("# ").strip()
                    parsed_data[current_device][key] = parsed_value
                else:
                    parsed_data[key] = parsed_value

    # Handle any remaining multiline entry at the end
    if in_multiline:
        if in_device:
            parsed_data[current_device][current_key] = "\n".join(
                multiline_value
            ).rstrip('"')
        else:
            parsed_data[current_key] = "\n".join(multiline_value).rstrip('"')

    return parsed_data


def _load_dict_from_hdf5(hdf5_file: h5py.File, root_group: str) -> dict:
    """
    Load a dictionary from an HDF5 file.

    This function reads data from an HDF5 file and returns it as a nested dictionary.
    It recursively traverses the HDF5 file structure, converting groups to subdictionaries
    and datasets to array-like objects.

    Parameters
    ----------
    hdf5_file : h5py.File
        An open HDF5 file object.
    root_group : str
        The name of the root group to start reading from.

    Returns
    -------
    dict
        A nested dictionary representing the structure and data of the HDF5 file.

    Notes
    -----
    This function assumes that the HDF5 file is already open when passed as an argument.
    It's the caller's responsibility to close the file after use.
    """

    def read_group(group: h5py.Group):
        """Recursively read an HDF5 group into a dictionary, including attributes."""
        d = {}

        # Read attributes from the group
        for key, value in group.attrs.items():
            d[key] = value

        # Read subgroups and datasets
        for key, item in group.items():
            if isinstance(item, h5py.Group):
                # Recursively read subgroups
                d[key] = read_group(item)
            elif isinstance(item, h5py.Dataset):
                # Read dataset as list
                d[key] = item[:]

        return d

    # Get the specified root group
    if root_group in hdf5_file:
        group = hdf5_file[root_group]
    else:
        raise KeyError(f"Group '{root_group}' not found in the HDF5 file.")

    return read_group(group)


def loadmatrix(filename, structured=True, print_header=False,
               replace_None=False):
    """
    Open matrix ascii data as well as hdf5 files generated by matrix.

    This utility function returns all header information as well as data as
    numpy.ndarray. Data fields should be addressed by column name
    (structured=True, default) or by index (structured=False).

    Parameters
    ----------
    filename : str
      path to file
    structured: {True, None}, optional
      controls whether a structured array or a plain numpy array is returned
    print_header : bool, optional
      if true, prints the column names read from the file together with their
      index
    replace_None : boolean, optional
      set to True to replace None values by 0 to allow plotting

    Returns
    -------
    header, data
    where header is a dictionary containing the header information. Most
    importantly it will contain a key 'columns' with a list of column names in
    the data object
    """
    tries = 0
    header = {"columns": [], "units": []}
    extension = os.path.splitext(filename)[-1]
    if detect_hdf5(filename):
        if not structured:
            raise NotImplementedError(
                "The option structured=False is not supported for hdf5 files")
        while tries < 10:
            # maximum number of tries to open the file is 10
            try:
                # use swmr read mode, to avoid corrupting the data during the
                # measurement (where it is written to by the matrix process)
                h5f = h5py.File(filename, 'r', swmr=True, libver='latest',
                                locking=False)
                break
            except OSError:
                # retry in case file is just written by the data acqusition
                tries += 1
        if 10 == tries:
            raise OSError("File could not be opened even after 10 tries")

        # generate header
        header["columns"] = list(h5f["data"].keys())
        header["units"] = [it.attrs["unit"] for it in h5f["data"].values()]
        header["comments"] = []
        header["status"] = None
        # check whether comments exist in file
        if "comments" in h5f:
            for entry in h5f["comments"]:
                message = entry[0].decode("utf-8")
                timestamp = entry[1].decode("utf-8")
                header["comments"].append(f"{timestamp}: {message}")
        for key, val in h5f.attrs.items():
            if val == "__None__":
                header[key] = None
            else:
                header[key] = val
        # parse System query entry into hierachical dictionary
        if extension.endswith("8"):
            header["system query"] = _load_dict_from_hdf5(h5f, "system query")
        h5g = h5f["data"]
        try:
            # generate data object as structured array
            dtypeslist = []
            # the following line relies on the fact that the first item has
            # the correct length, the code fails later if there are unequal
            # length
            npoints = len(list(h5g.values())[0])
            for name, v in h5g.items():
                if len(v.shape) == 1:
                    dtypeslist.append((name, v.dtype))
                else:
                    dtypeslist.append((name, v.dtype, v.shape[1:]))
            data = np.empty(npoints, dtype=np.dtype(dtypeslist))
            for name, v in h5g.items():
                data[name] = v[...]
        except ValueError:  # occurs for unequal data length in 1D arrays
            data = {name: v[...] for name, v in h5g.items()}
        h5f.close()

    else:
        with open(filename, "r") as matrix_file:
            headerlines = 0
            for nheader, line in enumerate(matrix_file):
                # parse header from lines that start with hashtag
                if "#" == line[0]:
                    if line[1] == "#":  # multiline entry
                        # strip header format characters
                        if sys.version_info.minor > 8:
                            # removeprefix/suffix introduced with python 3.9
                            strippedline = line.removesuffix("\n")[2:]
                        else:
                            # to be removed when python 3.8 is deprecated
                            strippedline = line.rstrip("\n")[2:]
                        if strippedline[0] == " ":
                            strippedline = strippedline[1:]
                        val += f"\n{strippedline}"
                        header[key] = val
                    else:
                        if sys.version_info.minor > 8:
                            # removeprefix/suffix introduced with python 3.9
                            strippedline = line.removeprefix("# ").removesuffix("\n")
                        else:
                            # to be removed when python 3.8 is deprecated
                            strippedline = line.lstrip("# ").rstrip("\n")
                        if strippedline == "Matrix outputfile":
                            # catches first line in legacy file format
                            continue
                        # split at " :" instead of ":" to avoid splitting the
                        # dcterms meta data
                        key, val = strippedline.split(" :", maxsplit=1)
                        key = key.strip()
                        if val.strip() == "None":
                            val = None
                        else:
                            val = val[1:]  # remove initial space
                        header[key] = val
                else:
                    if headerlines == 0:
                        header["columns"] = line.strip("\n").split("\t")
                    if headerlines == 1:
                        header["units"] = line.strip("\n").split("\t")
                    headerlines += 1
                    # for ma6, ma7 files the first three lines without hash
                    # are header lines
                    if headerlines == 3:
                        break
                    # ma8 files have only two header lines without hash
                    if extension.endswith("8") and headerlines == 2:
                        break
            # Read further special lines in the file
            special_lines = [
                (i, line) for i, line in enumerate(matrix_file) if line.startswith("#")
            ]
            # combine multiline comments and note after which datapoint the
            # comment was in the file
            header["comments"] = []
            header["status"] = None
            lastdpoint = -1
            for i, (linenr, msg) in enumerate(special_lines):
                dpoint = linenr - i
                if msg.startswith("# status:"):
                    header["status"] = msg.split(":", maxsplit=1)[1].strip()
                    continue
                if dpoint == lastdpoint:
                    if sys.version_info.minor > 8:
                        # removeprefix/suffix was introduced with python 3.9
                        message = msg.removeprefix("## ").removesuffix("\n")
                    else:
                        # to be removed when python 3.8 is deprecated
                        message = msg.lstrip("# ").rstrip("\n")
                    header["comments"][-1] += f"\n{message}"
                else:
                    if sys.version_info.minor > 8:
                        # removeprefix/suffix was introduced with python 3.9
                        message = msg.removeprefix("# ").removesuffix("\n")
                    else:
                        # to be removed when python 3.8 is deprecated
                        message = msg.lstrip("# ").rstrip("\n")
                    if message.startswith("comment ("):
                        m = re.search(r"\(([^)]+)\):\s(.*)", message)
                        header["comments"].append(
                            f"after {dpoint} points at {m.group(1)}: {m.group(2)}"
                        )
                    else:
                        raise ValueError("Unknown special line in matrix datafile")
                lastdpoint = dpoint
        # separate System query entry into hierachical dictionary
        if extension.endswith("8"):
            header["system query"] = _parse_query_string(
                header["system query"].replace(r"\"", '"')
            )
        for key, val in header.items():
            if isinstance(val, str):
                val = val.strip('"')  # strip " from header strings
                # remove escaping of other " in datafile
                val = val.replace(r"\"", '"')
                header[key] = val

        # we now have (i+1) as the number of lines to skip
        kwargs = {
            "sep": "\t",
            "low_memory": False,
            "comment": "#",
            "header": None,
        }
        if replace_None:
            kwargs['na_values'] = 'None'
        if structured is True:
            # generate a structured array with the column names as identifier
            kwargs["names"] = header["columns"]
        try:
            data = pd.read_csv(filename, skiprows=nheader + 1, **kwargs)
        except IndexError:
            # IndexError is raised in case an incomplete header is present
            print("loadmatrix: incomplete data file header")
            data = np.empty(0)
        if replace_None:
            # Define replacement values based on data types
            replacement_values = {
                'bool': False,
                'int': -1,
                'float': np.nan,
                'object': 'NaN',  # 'object' dtype is often used for strings in Pandas
            }
            # Replace missing values
            for column in data.columns:
                if pd.api.types.is_bool_dtype(data[column]):
                    data[column] = data[column].fillna(
                        replacement_values['bool'])
                elif pd.api.types.is_integer_dtype(data[column]):
                    data[column] = data[column].fillna(
                        replacement_values['int'])
                elif pd.api.types.is_float_dtype(data[column]):
                    data[column] = data[column].fillna(
                        replacement_values['float'])
                elif pd.api.types.is_object_dtype(data[column]):
                    data[column] = data[column].fillna(
                        replacement_values['object'])
        if structured is True:
            data = data.to_records(index=False)
        else:
            data = data.to_numpy()

    if print_header is True:
        # generate list of tuples with index and column name
        print(list(enumerate(header["columns"])))
    return header, data


def loadh5matrix(filename, filehandle=False):
    """
    Load matrix data is hdf5 format.

    Note: This utility function is deprecated and is replaced by loadmatrix(filename)!
    """
    if filehandle:
        raise NotImplementedError(
            """
            use h5py.File(filename, 'r', swmr=True, libver='latest') to open
            the datafile for reading if loadmatrix is not sufficient.
            """)
    warnings.warn(
        "loadh5matrix will be removed soon. use loadmatrix instead")
    return loadmatrix(filename)


