def detect_hdf5(filename):
    file = open(filename, "rb")
    first_bytes = file.read(4)
    file.close()
    if (first_bytes == b'\x89HDF'):
        return True
    else:
        return False


def get_latest_datafile(path=None, basename=None):
    """
    automagically find latest datafile in 'path' which follows the pattern of
    'basename'. Note that a trailing "_[integer]" is removed from basename to
    find the latest file recorded with the same basename.

    If path is None the path is taken from 'basename'. 'basename' can be an
    input file name or a data file name which was given to matrix. If no
    basename is given the latest data file by creation date will be returned in
    path. If both path and basename are None os.curdir will be used.

    Parameters
    ----------
    path: str or None, optional
      path in which the latest datafile should be determined
    baesname: str or None, optional
      an example filename or input filename used to filter files in path.
    """
    if basename:
        basepath, basefilename = split(basename)
        basewoext = splitext(basefilename)[0]
        basewoext = re.sub(r"(_\d+)$", "", basewoext)

    # determine used file path
    if path:
        usedpath = path
    elif basename and basepath:
        usedpath = basepath
    else:
        usedpath = os.curdir

    # obtain file list and filter it
    allfiles = os.listdir(usedpath)
    filelist = filter(lambda f: isfile(join(usedpath, f)), allfiles)
    if basename and basewoext:  # filter file list by file extension/basename
        files = natsorted(
            [f for f in filelist if
             re.search(fr'^({basewoext})(_\d+)?(\.h5)?\.ma\d$', f)]
        )
    else:  # filter by file extension and sort by date
        files = sorted(
            [f for f in filelist if re.search(r'(_\d+)?(\.h5)?\.ma\d$', f)],
            key=lambda f: os.path.getctime(join(usedpath, f))
        )

    if len(files) > 0:
        return join(usedpath, files[-1])
    else:
        return None


def loadmatrix(filename, structured=True, print_header=False):
    """
    Utility function to open matrix ascii data as well as hdf5 files generated
    by matrix.

    Returns all header information as well as data as numpy.ndarray. Data
    fields should be addressed by column name (structured=True, default) or by
    index (structured=False).

    Parameters
    --------
    filename : str
      path to file
    structured: {True, None}, optional
      controls whether a structured array or a plain numpy array is returned
    print_header : bool, optional
      if true, prints the column names read from the file together with their
      index

    Returns
    -------
    header, data
    where header is a dictionary containing the header information. Most
    importantly it will contain a key 'columns' with a list of column names in
    the data object
    """
    tries = 0
    header = dict(columns=[], units=[])
    if detect_hdf5(filename):
        if 'h5py' not in sys.modules:
            # disable file locking in h5py
            # seems this is needed before loading the package
            os.environ["HDF5_USE_FILE_LOCKING"] = "FALSE"  # noqa
            import h5py  # this import does not generate a global variable

            # in the scope of the calling program?!
        elif 'h5py' not in globals():
            # workaround for previous comment on import
            h5py = sys.modules['h5py']
        if not structured:
            raise NotImplementedError(
                "The option structured=False is not supported for hdf5 files")
        while tries < 10:
            # maximum number of tries to open the file is 10
            try:
                # use swmr read mode, to avoid corrupting the data during the
                # measurement (where it is written to by the matrix process)
                h5f = h5py.File(filename, 'r', swmr=True, libver='latest')
                break
            except OSError:
                # retry in case file is just written by the data acqusition
                tries += 1
        if 10 == tries:
            raise OSError("File could not be opened even after 10 tries")

        # generate header
        header['columns'] = [key for key in h5f["data"].keys()]
        header['units'] = [it.attrs["unit"] for it in h5f["data"].values()]
        for key, val in h5f.attrs.items():
            if val == "__None__":
                header[key] = None
            else:
                header[key] = val

        h5g = h5f["data"]
        try:
            # generate data object as structured array
            dtypeslist = []
            # the following line relies on the fact that the first item has
            # the correct length, the code fails later if there are unequal
            # length
            npoints = len(list(h5g.values())[0])
            for name, v in h5g.items():
                if len(v.shape) == 1:
                    dtypeslist.append((name, v.dtype))
                else:
                    dtypeslist.append((name, v.dtype, v.shape[1:]))
            data = np.empty(npoints, dtype=np.dtype(dtypeslist))
            for name, v in h5g.items():
                data[name] = v[...]
        except ValueError:  # occurs for unequal data length in 1D arrays
            data = {name: v[...] for name, v in h5g.items()}
        h5f.close()

    else:
        with open(filename, "r") as matrixFile:
            headerlines = 0
            depth = 0
            for i, line in enumerate(matrixFile):
                # parse header from lines that start with hashtag
                if "#" == line[0]:
                    if line[depth+1] == '#':  # multiline entry
                        # strip header format characters
                        strippedline = line.lstrip('#').rstrip('\n')[1:]
                        val += f"\n{strippedline}"
                        header[key] = val
                    else:
                        strippedline = line.lstrip("# ").rstrip('\n')
                        if strippedline == "Matrix outputfile":
                            # catches first line in legacy file format
                            continue
                        key, val = strippedline.split(':', maxsplit=1)
                        key = key.strip()
                        if val.strip() == "None":
                            val = None
                        else:
                            val = val[1:]  # remove initial space
                        header[key] = val
                else:
                    # the first three lines without hashtag are header lines
                    if headerlines == 0:
                        header["columns"] = line.strip("\n").split("\t")
                    if headerlines == 1:
                        header["units"] = line.strip("\n").split("\t")
                    headerlines += 1
                    if headerlines == 3:
                        break
        for key, val in header.items():
            if isinstance(val, str):
                header[key] = val.strip('"')  # strip " from header strings

        # we now have (i+1) as the number of lines to skip
        if structured is True:
            # generate a structured array with the column names as identifier
            try:
                data = np.genfromtxt(filename, skip_header=i,
                                     delimiter="\t", names=structured,
                                     dtype=None)
            except IndexError:
                # IndexError is raised in case an incomplete header is present
                print("loadmatrix: incomplete data file header")
                data = np.empty(0)
            if data.dtype.names is not None:
                header["columns"] = data.dtype.names
            else:
                header["columns"] = []
        else:
            # otherwise generates a plain array only from the data
            data = np.genfromtxt(filename, skip_header=i+1, delimiter="\t")

    if print_header is True:
        # generate list of tuples with index and column name
        print([(i, col) for (i, col) in enumerate(header["columns"])])
    return header, data


def loadh5matrix(filename, filehandle=False):
    """
    Utility function to load matrix data is hdf5 format.

    Note: This function is deprecated and is replaced by loadmatrix(filename)!
    """
    if filehandle:
        raise NotImplementedError(
            """
            use h5py.File(filename, 'r', swmr=True, libver='latest') to open
            the datafile for reading if loadmatrix is not sufficient.
            """)
    else:
        warnings.warn(
            "loadh5matrix will be removed soon. use loadmatrix instead")
        return loadmatrix(filename)


